"""
Tests for simulation.py, based on Tests.xlsx sections 5.1 - 5.5.

Note: unlike earlier sections, these tests cannot check for an exact match
against `testout_5.x.csv`. Those files hold the covariance of *one*
particular 100,000-draw random sample (generated by a different RNG
implementation), so they are themselves only approximately equal to the
true input covariance -- not a deterministic function of the input we can
reproduce exactly. Instead, each test simulates its own 100,000 draws
(with a fixed seed for reproducibility of the test) and checks that the
*empirical* covariance of the simulated draws is close to the covariance
that was supposed to be simulated from (the input, optionally passed
through a PSD fix first), within the tolerance expected from Monte Carlo
sampling noise at that sample size.
"""

import os

import numpy as np
import pandas as pd
import pytest

from conftest import TEST_FILES_DIR
from psd_fix import fix_psd_matrix
from simulation import simulate_normal

NUM_SIMULATIONS = 100_000
SEED = 1
# Empirically, max abs error between the true and 100,000-draw empirical
# covariance for these test matrices is on the order of 1e-3 to 1e-2; 0.03
# gives comfortable headroom without being so loose it'd miss a real bug.
ATOL = 0.03


def load_csv(name):
    return pd.read_csv(os.path.join(TEST_FILES_DIR, name))


def test_simulate_normal_direct_pd_input():
    # Test 5.1: Normal simulation, PD input, 0 mean
    cov = load_csv("test5_1.csv")

    draws = simulate_normal(cov, num_simulations=NUM_SIMULATIONS, seed=SEED)

    assert np.allclose(draws.cov().values, cov.values, atol=ATOL)


def test_simulate_normal_direct_psd_input():
    # Test 5.2: Normal simulation, PSD input, 0 mean
    cov = load_csv("test5_2.csv")

    draws = simulate_normal(cov, num_simulations=NUM_SIMULATIONS, seed=SEED)

    assert np.allclose(draws.cov().values, cov.values, atol=ATOL)


def test_simulate_normal_near_psd_fix():
    # Test 5.3: Normal simulation, non-PSD input repaired with near_psd
    cov = load_csv("test5_3.csv")
    target = fix_psd_matrix(cov, method="near_psd")

    draws = simulate_normal(
        cov, num_simulations=NUM_SIMULATIONS, psd_fix="near_psd", seed=SEED
    )

    assert np.allclose(draws.cov().values, target.values, atol=ATOL)


def test_simulate_normal_higham_fix():
    # Test 5.4: Normal simulation, non-PSD input repaired with Higham's method
    cov = load_csv("test5_3.csv")
    target = fix_psd_matrix(cov, method="higham")

    draws = simulate_normal(
        cov, num_simulations=NUM_SIMULATIONS, psd_fix="higham", seed=SEED
    )

    assert np.allclose(draws.cov().values, target.values, atol=ATOL)


def test_simulate_normal_pca():
    # Test 5.5: PCA simulation, 99% explained variance, 0 mean
    cov = load_csv("test5_2.csv")

    draws = simulate_normal(
        cov,
        num_simulations=NUM_SIMULATIONS,
        method="pca",
        explained_variance=0.99,
        seed=SEED,
    )

    assert np.allclose(draws.cov().values, cov.values, atol=ATOL)


def test_simulate_normal_pca_uses_fewer_components_than_full_rank():
    # Sanity check on the PCA reduction itself: asking for less than 100%
    # explained variance on a 5-variable input should keep < 5 components.
    cov = load_csv("test5_2.csv")

    draws = simulate_normal(
        cov, num_simulations=10, method="pca", explained_variance=0.5, seed=SEED
    )

    assert draws.shape == (10, cov.shape[1])


def test_simulate_normal_invalid_method():
    cov = load_csv("test5_1.csv")
    with pytest.raises(ValueError):
        simulate_normal(cov, method="not_a_real_method")
